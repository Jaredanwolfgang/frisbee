const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {search,context}=require('../dist/rules-search.js'),data=require('../dist/wfdf/index.json'),entries=data.entries;
const core=entries.filter(e=>e.doc==='core'&&e.chapter!=='definitions');
assert.equal(data.chapters.length,20);assert.equal(core.length,368);assert.equal(core.filter(e=>e.zh).length,367);
assert.equal(new Set(entries.map(e=>e.key)).size,entries.length);
for(const [query,ref] of [['走步','18.2'],['Pick','18.3'],['同时接盘','12.3'],['18.2.1','18.2.1'],['TRAVEL','18.2'],['危险动作','17.1']]) assert.equal(search(entries,query)[0].ref,ref,query);
assert(search(entries,'接盘后可以走几步').some(e=>e.ref==='18.2.1.1.2'));
assert(search(entries,'double team').some(e=>e.ref==='18.1.1.5'));
assert(search(entries,'zzzz no such term').length===0);
assert(search(entries,'', {scope:'core',chapter:'11'}).every(e=>e.chapter==='11'));
const child=core.find(e=>e.ref==='18.2.1.1.2'),family=context(entries,child);
assert(family.some(e=>e.ref==='18.2.1.1.1'));assert(family.some(e=>e.ref==='18.2.7'));assert(family.every(e=>e.ref.startsWith('18.2')));
assert(core.find(e=>e.ref==='12.3').zh.includes('进攻方拥有盘权'));
assert(core.find(e=>e.ref==='1.10').en.endsWith('best perspective on the play.'));
assert(!core.find(e=>e.ref==='19.2.1.1').zh);
assert.equal(entries.filter(e=>e.doc==='annotations').length,147);
assert(search(entries,'走步',{scope:'annotations'}).length>0);
assert(search(entries,'男女比例',{scope:'appendix'}).length>0);
assert(search(entries,'A12.2',{scope:'appendix'}).some(e=>e.en.includes('TRG')));
assert(entries.every(e=>!e.en?.includes("Steinar's comment")));
assert(entries.every(e=>e.url.startsWith('https://urules.org/')||e.url.startsWith('https://rules.wfdf.sport/')));
assert(!fs.readdirSync(path.join(__dirname,'../dist/wfdf')).some(f=>f.endsWith('.pdf')));
console.log('PASS: 368 clauses / 20 chapters, bilingual coverage, current source attribution, topic/ID searches, exceptions in context, 147 annotations and v2.0 appendix; no PDF assets.');
